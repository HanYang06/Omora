#!/usr/bin/env python3
"""从 protocol/*.schema.json 生成 TypeScript 类型。

唯一真相是 schema；生成物必须与它一致。门禁跑 --check，diff 非空即失败。
用法：uv run python scripts/gen_contract.py [--check]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any, cast

ROOT = Path(__file__).resolve().parents[1]
PROTOCOL = ROOT / "protocol"
OUTPUT = PROTOCOL / "generated" / "contract.ts"

JsonObject = dict[str, Any]
IDENTIFIER = re.compile(r"^[A-Za-z_$][\w$]*$")
SCALARS = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}

HEADER = """// AUTO-GENERATED by scripts/gen_contract.py -- do not edit.
// Source of truth: protocol/*.schema.json
// Regenerate: uv run python scripts/gen_contract.py
"""


def load(path: Path) -> JsonObject:
    return cast("JsonObject", json.loads(path.read_text(encoding="utf-8")))


def literal(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if value is None:
        return "null"
    return str(value)


def ref_name(ref: str, root_name: str) -> str:
    if ref == "#":
        return root_name
    prefix = "#/$defs/"
    if not ref.startswith(prefix):
        raise SystemExit(f"无法解析的 $ref: {ref}")
    return ref.removeprefix(prefix)


def wrap(node: str) -> str:
    return f"({node})" if " | " in node else node


def object_type(schema: JsonObject, root_name: str) -> str:
    properties: JsonObject = schema.get("properties", {})
    required = set(cast("list[str]", schema.get("required", [])))
    if not properties:
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"Record<string, {ts_type(cast('JsonObject', extra), root_name)}>"
        return "Record<string, unknown>"
    fields = [
        f"{key}{'' if key in required else '?'}: {ts_type(cast('JsonObject', value), root_name)}"
        for key, value in properties.items()
    ]
    return "{ " + "; ".join(fields) + " }"


def by_type(schema: JsonObject, root_name: str) -> str:
    kind = schema["type"]
    if isinstance(kind, list):
        return " | ".join(by_type({"type": item}, root_name) for item in cast("list[str]", kind))
    if kind == "array":
        items = cast("JsonObject", schema.get("items", {"type": "unknown"}))
        return f"{wrap(ts_type(items, root_name))}[]"
    if kind == "object":
        return object_type(schema, root_name)
    return SCALARS.get(cast("str", kind), "unknown")


def ts_type(schema: JsonObject, root_name: str) -> str:
    if "$ref" in schema:
        return ref_name(cast("str", schema["$ref"]), root_name)
    if "const" in schema:
        return literal(schema["const"])
    if "enum" in schema:
        return " | ".join(literal(item) for item in cast("list[object]", schema["enum"]))
    if "oneOf" in schema:
        items = cast("list[JsonObject]", schema["oneOf"])
        return " | ".join(ts_type(item, root_name) for item in items)
    if "type" in schema:
        return by_type(schema, root_name)
    return "unknown"


def field_name(name: str) -> str:
    return name if IDENTIFIER.match(name) else json.dumps(name, ensure_ascii=False)


def render_union(schema: JsonObject, root_name: str) -> str:
    items = cast("list[JsonObject]", schema["oneOf"])
    body = "\n  | " + "\n  | ".join(ts_type(item, root_name) for item in items)
    return body + ";"


def render_def(name: str, schema: JsonObject, root_name: str) -> str:
    properties = schema.get("properties")
    if properties and schema.get("type", "object") == "object":
        required = set(cast("list[str]", schema.get("required", [])))
        fields: list[str] = []
        for key, value in cast("JsonObject", properties).items():
            optional = "" if key in required else "?"
            fields.append(
                f"  {field_name(key)}{optional}: {ts_type(cast('JsonObject', value), root_name)};"
            )
        return "export interface " + name + " {\n" + "\n".join(fields) + "\n}"
    if "oneOf" in schema:
        return f"export type {name} ={render_union(schema, root_name)}"
    return f"export type {name} = {ts_type(schema, root_name)};"


def render_schema(path: Path) -> tuple[str, list[str]]:
    schema = load(path)
    root_name = cast("str", schema["title"])
    blocks: list[str] = [render_def(root_name, schema, root_name)]
    defs = cast("JsonObject", schema.get("$defs", {}))
    for name, body in defs.items():
        blocks.append(render_def(name, cast("JsonObject", body), root_name))
    names = [root_name, *defs]
    return "\n\n".join(blocks), names


def render() -> str:
    batches: list[str] = []
    seen: dict[str, str] = {}
    for path in sorted(PROTOCOL.glob("*.schema.json")):
        text, names = render_schema(path)
        for name in names:
            if name in seen:
                raise SystemExit(f"类型名重复: {name}（{seen[name]} 与 {path.name}）")
            seen[name] = path.name
        batches.append(text)
    return HEADER + "\n" + "\n\n".join(batches) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUTPUT.is_file():
            print(
                f"缺少生成物 {OUTPUT.relative_to(ROOT)}；运行 uv run python scripts/gen_contract.py"
            )
            return 1
        current = OUTPUT.read_text(encoding="utf-8")
        if current != text:
            print("契约生成物与 schema 不一致；先运行 scripts/gen_contract.py 再提交。")
            return 1
        print("contract.types: 生成物与 schema 一致")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
